    def _create_recipes(self, cooks, cuisines, tags):
        recipes = []
        for data in RECIPES:
            if Recipe.objects.filter(name=data["name"]).exists():
                recipes.append(Recipe.objects.get(name=data["name"]))
                continue

            cuisine = cuisines.get(data["cuisine"])
            recipe = Recipe.objects.create(
                name=data["name"],
                description=data["description"],
                ingredients=data["ingredients"],
                instructions=data["instructions"],
                cooking_time=data["cooking_time"],
                cuisine=cuisine,
                author=random.choice(cooks),
                image=get_sample_image(),
            )

            recipe_tags = [tags[t] for t in data["tags"] if t in tags]
            recipe.tags.set(recipe_tags)
            recipes.append(recipe)

        self.stdout.write(f"Створено рецептів: {len(recipes)}")
        return recipes

